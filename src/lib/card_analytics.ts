function isGradeable(score: QueueInteractionScore): boolean {
  return (
    score === QueueInteractionScore.AGAIN ||
    score === QueueInteractionScore.HARD ||
    score === QueueInteractionScore.GOOD ||
    score === QueueInteractionScore.EASY
  );
}

function gradeValue(score: QueueInteractionScore): number | null {
  switch (score) {
    case QueueInteractionScore.AGAIN: return 1;
    case QueueInteractionScore.HARD: return 2;
    case QueueInteractionScore.GOOD: return 3;
    case QueueInteractionScore.EASY: return 4;
    default: return null;
  }
}

function computeCardStats(
  card: any,
  weights: number[] | null,
  now: number,
  cardCapMs: number,
  ignorePreReset: boolean,
  startMs: number,
  endMs: number,
  isPaused: boolean,
): PerCardStats {
  const history = card.repetitionHistory ?? [];
  const sorted = [...history].sort((a: any, b: any) => a.date - b.date);

  // Effective history = post-RESET slice when the toggle is on, else the full
  // history. FSRS replay below also uses the effective history so D/R/S and
  // Avg pR stay consistent with the reps actually being counted.
  let effective: any[] = sorted;
  if (ignorePreReset) {
    const lastResetIdx = sorted.map((h: any) => h.score).lastIndexOf(QueueInteractionScore.RESET);
    if (lastResetIdx !== -1) effective = sorted.slice(lastResetIdx + 1);
  }

  const inPeriod = (h: any) => h && typeof h.date === 'number' && h.date >= startMs && h.date < endMs;
  const isAllPeriod = startMs <= 0;

  // ---- Period-filtered tallies (Reps, Time, Lapses, Retention, Grade) ----
  let gradeableReps = 0;
  let totalTimeMs = 0;
  let mainReps = 0;
  let agains = 0;
  let sumGrade = 0;
  let gradeCount = 0;

  for (const h of effective) {
    if (!isGradeable(h.score)) continue;
    if (!inPeriod(h)) continue;
    gradeableReps++;
    const t = Math.min(Math.max(0, h.responseTime || 0), cardCapMs);
    totalTimeMs += t;
    if (!countsForMainCard(h)) continue;
    mainReps++;
    if (h.score === QueueInteractionScore.AGAIN) agains++;
    const g = gradeValue(h.score);
    if (g !== null) {
      sumGrade += g;
      gradeCount++;
    }
  }
  const lapses = agains;

  // ---- Always-current population flags (isNew, isDue, isStale) ------------
  //
  // %New / %Stale / Due describe the card's CURRENT state in the KB — they
  // don't shift when the user narrows the period. A card with reviews from
  // years ago but none in "This Week" should not count as new.
  let everGradeable = false;
  for (const h of effective) {
    if (isGradeable(h.score)) { everGradeable = true; break; }
  }
  const isNew = !everGradeable;

  const nextRep = card.nextRepetitionTime as number | undefined;
  const isDue = (nextRep ?? Infinity) <= now;

  let isStale = false;
  const lastRep = effective.length > 0 ? effective[effective.length - 1] : null;
  if (lastRep && nextRep && nextRep > lastRep.date) {
    const lastInterval = nextRep - lastRep.date;
    const staleDate = lastRep.date + 2 * lastInterval;
    isStale = now > staleDate;
  }

  // ---- Cost ---------------------------------------------------------------
  // Period = 'all' → existing per-card coverage formula (lifetime cost).
  // Finite period → annualized: time spent in period / period length in years.
  let cost: number | null = null;
  if (totalTimeMs > 0) {
    const totalMinutes = totalTimeMs / 60000;
    const yearMs = 1000 * 60 * 60 * 24 * 365;
    if (isAllPeriod) {
      let firstGradeableDate: number | null = null;
      for (const h of effective) {
        if (isGradeable(h.score)) { firstGradeableDate = h.date; break; }
      }
      if (firstGradeableDate) {
        if (nextRep && nextRep > now) {
          const coverageYears = (nextRep - firstGradeableDate) / yearMs;
          if (coverageYears > 0) cost = totalMinutes / coverageYears;
        } else {
          const ageYears = (now - firstGradeableDate) / yearMs;
          if (ageYears > 0) cost = totalMinutes / ageYears;
        }
      }
    } else {
      const periodYears = (endMs - startMs) / yearMs;
      if (periodYears > 0) cost = totalMinutes / periodYears;
    }
  }

  // ---- FSRS state + Avg pR ------------------------------------------------
  // FSRS state (D / R today / S) is always-current — replayed over the full
  // effective history regardless of period.
  // Avg pR (predicted retrievability at the moment of each rep) is averaged
  // only over reps in the period — same period filter as Reps/Time/Retention.
  let sumPredR = 0;
  let predRCount = 0;
  let d: number | null = null;
  let s: number | null = null;
  let rToday: number | null = null;

  if (!isNew) {
    try {
      // Main-card reps only, so `steps` and the walk below index the same list.
      const mainHistory = effective.filter(countsForMainCard);
      const steps = computeFSRSStatesPerReview(mainHistory, weights);
      // FSRS leaves step.r null for learning/relearning state reps; we want
      // Avg pR's denominator to match Retention's (every gradeable rep except
      // the first of each FSRS "lifetime"), so we compute the forgetting-curve
      // r ourselves for those cases using the previous gradeable rep's stability.
      const { w } = resolveWeights(weights);
      const DECAY = -w[20];
      const FACTOR = Math.pow(0.9, 1 / DECAY) - 1;

      let lastGradeableIdx: number | null = null;
      for (let i = 0; i < mainHistory.length; i++) {
        const h = mainHistory[i];

        // RESET ends the current "lifetime" — the next gradeable rep is
        // effectively a brand-new card and gets skipped just like the first
        // rep of a fresh card.
        if (h.score === QueueInteractionScore.RESET) {
          lastGradeableIdx = null;
          continue;
        }
        if (!isGradeable(h.score)) continue;

        // First gradeable rep of this lifetime: no prior FSRS state to predict
        // from. Per design, we skip it (no contribution to numerator or
        // denominator), but still advance the reference for downstream reps.
        if (lastGradeableIdx === null) {
          lastGradeableIdx = i;
          continue;
        }

        if (inPeriod(h)) {
          const step = steps[i];
          let r: number | null = step?.r ?? null;
          if (r === null) {
            // Learning/relearning rep: replicate the FSRS forgetting curve
            // using the previous gradeable rep's stability.
            const prevS = steps[lastGradeableIdx]?.s ?? 0;
            const prevDate = mainHistory[lastGradeableIdx].date;
            const elapsedDays = (h.date - prevDate) / (1000 * 60 * 60 * 24);
            if (prevS > 0 && elapsedDays >= 0) {
              r = forgettingCurve(elapsedDays, prevS, DECAY, FACTOR);
            }
          }
          if (r !== null && Number.isFinite(r)) {
            sumPredR += r;
            predRCount++;
          }
        }

        lastGradeableIdx = i;
      }

      const state = computeFSRSState(effective, weights);
      if (state) {
        d = state.d;
        s = state.s;
        rToday = state.r;
      }
    } catch {
      // FSRS failure on a single card is non-fatal — its FSRS-derived stats just stay null.
    }
  }

  return {
    isDue,
    isNew,
    isStale,
    isUnscheduled: nextRep === null || nextRep === undefined,
    isPaused,
    gradeableReps,
    totalTimeMs,
    mainReps,
    agains,
    lapses,
    cost,
    sumPredR,
    predRCount,
    sumGrade,
    gradeCount,
    d,
    s,
    rToday,
  };
}

function accumulate(acc: AccData, stats: PerCardStats, priority: number) {
  acc.count++;
  if (priority < acc.minPriority) acc.minPriority = priority;
  if (priority > acc.maxPriority) acc.maxPriority = priority;
  // A card in a paused deck may also be unscheduled. Count it once, under
  // `paused`: the pause explains the whole subtree and is the thing to undo.
  if (stats.isPaused) acc.paused++;
  else if (stats.isUnscheduled) acc.unscheduled++;

  // Paused cards count as due, new and stale exactly like any other card.
  // Pausing defers work; it does not cancel it, and it does not un-forget the
  // card. Excluding them would mean pausing a backlog-heavy deck instantly
  // improved every statistic here — and unpausing undid the improvement — so
  // these numbers would move for reasons that have nothing to do with studying.
  // Only UNSCHEDULED cards are left out, and they are left out of the
  // denominator too: those are not deferred work, they are not work at all.
  if (stats.isDue) acc.due++;
  if (stats.isNew) {
    if (stats.isUnscheduled) acc.newUnscheduled++;
    else acc.newCount++;
  }
  if (stats.isStale) acc.staleCount++;

  acc.totGradeableReps += stats.gradeableReps;
  acc.totTimeMs += stats.totalTimeMs;
  acc.totMainReps += stats.mainReps;
  acc.totAgains += stats.agains;

  if (!stats.isNew) {
    acc.totLapses += stats.lapses;
    acc.nonNewCards++;
  }
  if (stats.cost !== null) {
    acc.sumCost += stats.cost;
    acc.cardsWithCost++;
  }

  acc.sumPredR += stats.sumPredR;
  acc.predRCount += stats.predRCount;
  acc.sumGrade += stats.sumGrade;
  acc.gradeCount += stats.gradeCount;

  // FSRS state covers everything still in the workload, paused decks included:
  // their retrievability really is decaying, and hiding that would make a
  // parked deck look healthier than it is. Only unscheduled cards are left out.
  if (!stats.isUnscheduled && stats.d !== null && stats.s !== null && stats.rToday !== null) {
    acc.sumD += stats.d;
    acc.sumS += stats.s;
    acc.sumRtoday += stats.rToday;
    acc.fsrsCount++;
  }
}

function finalize(acc: AccData, label: string): CardBucketStats {
  const cards = acc.count;
  const priorityRange =
    cards > 0 && Number.isFinite(acc.minPriority) && Number.isFinite(acc.maxPriority)
      ? `${acc.minPriority}-${acc.maxPriority}`
      : '—';
  // Denominator = the cards still in the workload: everything except the
  // unscheduled ones. Counting unscheduled cards as "done" reported 100% for
  // buckets holding hundreds of cards no queue will ever show; counting paused
  // ones out would make pausing a deck look like progress.
  const counted = cards - acc.unscheduled;
  // Reported separately: what the queue could serve today. Not a denominator —
  // see the note above.
  const active = counted - acc.paused;
  const donePct = counted > 0 ? ((counted - acc.due) / counted) * 100 : 100;
  const newPct = counted > 0 ? (acc.newCount / counted) * 100 : 0;
  const stalePct = counted > 0 ? (acc.staleCount / counted) * 100 : 0;
  const avgReps = cards > 0 ? acc.totGradeableReps / cards : 0;
  const avgTimeMs = cards > 0 ? acc.totTimeMs / cards : 0;
  const cpm = acc.totTimeMs > 0 ? acc.totGradeableReps / (acc.totTimeMs / 60000) : 0;
  const avgTimePerRepMs = acc.totGradeableReps > 0 ? acc.totTimeMs / acc.totGradeableReps : 0;
  const avgCost = acc.cardsWithCost > 0 ? acc.sumCost / acc.cardsWithCost : 0;
  const avgLapses = acc.nonNewCards > 0 ? acc.totLapses / acc.nonNewCards : 0;
  const retention =
    acc.totMainReps > 0
      ? ((acc.totMainReps - acc.totAgains) / acc.totMainReps) * 100
      : 0;
  const avgPredR = acc.predRCount > 0 ? (acc.sumPredR / acc.predRCount) * 100 : 0;
  // R-deviation only meaningful when both retention and predicted R have a basis.
  const rDevPP = acc.totMainReps > 0 && acc.predRCount > 0 ? retention - avgPredR : 0;
  const avgGrade = acc.gradeCount > 0 ? acc.sumGrade / acc.gradeCount : 0;
  const avgD = acc.fsrsCount > 0 ? acc.sumD / acc.fsrsCount : 0;
  const avgS = acc.fsrsCount > 0 ? acc.sumS / acc.fsrsCount : 0;
  const avgRtoday = acc.fsrsCount > 0 ? (acc.sumRtoday / acc.fsrsCount) * 100 : 0;

  return {
    label,
    priorityRange,
    cards,
    unscheduled: acc.unscheduled,
    paused: acc.paused,
    active,
    due: acc.due,
    donePct,
    newCount: acc.newCount,
    newPct,
    newUnscheduled: acc.newUnscheduled,
    staleCount: acc.staleCount,
    stalePct,
    totReps: acc.totGradeableReps,
    totTimeMs: acc.totTimeMs,
    avgReps,
    avgTimeMs,
    cpm,
    avgTimePerRepMs,
    avgCostMinPerYear: avgCost,
    avgLapses,
    retention,
    avgPredR,
    rDevPP,
    avgGrade,
    avgD,
    avgRtoday,
    avgS,
  };
}

/**
 * Replay FSRS over every card and aggregate per priority-percentile bucket.
 *
 * The expensive part is `plugin.card.getAll()` (one call) and the per-card
 * FSRS replay (CPU only — no further async). We yield to the event loop every
 * `YIELD_EVERY` cards so the popup stays responsive while progress updates.
 */
export interface PeriodSpec {
  /** Period id (e.g. 'thisYear'). Stored on the breakdown for cache-sync. */
  id: string;
  startMs: number;
  endMs: number;
  customStart: string;
  customEnd: string;
}

/**
 * One exported row per card — the raw material behind every aggregate above.
 * Emitted through the optional `onRow` callback so an export can reuse the
 * exact same population, priority inheritance, bucketing and New/Due/Stale
 * predicates the table renders (no second, drifting implementation).
 */
export interface CardAnalyticsRow {
  cardId: string;
  remId: string;
  cardType: string;
  /** For cloze cards, the cloze id the card is bound to; null otherwise. It is
   *  what lets us ask whether the Rem's text still contains this card's markup. */
  clozeId: string | null;
  /** Inherited priority of the owning Rem (1-100). */
  priority: number;
  /** 1-based rank percentile within the sorted card population (0-100). */
  percentile: number;
  /** Bucket label the card was counted in, e.g. "0-10%". */
  bucket: string;
  isNew: boolean;
  isDue: boolean;
  isStale: boolean;
  /**
   * Why the card is / isn't due, from `nextRepetitionTime` alone:
   * - `unscheduled` — null/undefined next time. RemNote leaves this empty for
   *   cards it will never surface: disabled practice direction, and some
   *   never-scheduled states. These can never be Due, so no queue and no
   *   Priority Review Document will ever pick them up.
   * - `due` — next time ≤ now.
   * - `scheduled` — next time in the future.
   */
  scheduleState: 'unscheduled' | 'due' | 'scheduled';
  /**
   * Inside a paused deck. Schedulable — pausing does not clear
   * `nextRepetitionTime` — but the queue will not serve it. Always false when no
   * paused-deck scan was supplied.
   */
  inPausedDeck: boolean;
  /** Raw next repetition time (ms epoch) or null. */
  nextRepetitionTime: number | null;
  createdAt: number | null;
  /** Total history entries (every interaction, gradeable or not). */
  historyEntries: number;
  /** Gradeable reps over the FULL lifetime (ignores period AND ignorePreReset). */
  gradeableRepsLifetime: number;
  /** Gradeable reps in the effective slice — what `isNew` actually looks at. */
  gradeableRepsEffective: number;
  /** True when the history contains at least one RESET entry. */
  hasReset: boolean;
  /** Non-gradeable interactions (SKIP / TOO_SOON / RESET / VIEWED…) lifetime. */
  nonGradeableInteractions: number;
  /** Score of the last history entry, or null when there is no history. */
  lastScore: number | null;
  lastInteractionDate: number | null;
}

/**
 * Lifetime + effective history facts for one card. Kept next to
 * `computeCardStats` so the RESET slicing rule stays defined in one place.
 */
function describeCardHistory(card: any, ignorePreReset: boolean) {
  const history: any[] = card.repetitionHistory ?? [];
  const sorted = [...history].sort((a: any, b: any) => a.date - b.date);
  let effective = sorted;
  if (ignorePreReset) {
    const lastResetIdx = sorted.map((h: any) => h.score).lastIndexOf(QueueInteractionScore.RESET);
    if (lastResetIdx !== -1) effective = sorted.slice(lastResetIdx + 1);
  }
  let gradeableRepsLifetime = 0;
  let hasReset = false;
  for (const h of sorted) {
    if (isGradeable(h.score)) gradeableRepsLifetime++;
    if (h.score === QueueInteractionScore.RESET) hasReset = true;
  }
  let gradeableRepsEffective = 0;
  for (const h of effective) if (isGradeable(h.score)) gradeableRepsEffective++;
  const last = sorted.length > 0 ? sorted[sorted.length - 1] : null;
  return {
    historyEntries: sorted.length,
    gradeableRepsLifetime,
    gradeableRepsEffective,
    hasReset,
    nonGradeableInteractions: sorted.length - gradeableRepsLifetime,
    lastScore: last ? (last.score as number) : null,
    lastInteractionDate: last ? (last.date as number) : null,
  };
}

function cardTypeLabel(type: any): string {
  if (typeof type === 'string') return type;
  if (type && typeof type === 'object' && 'clozeId' in type) return 'cloze';
  return 'unknown';
}

export async function computeCardAnalyticsBreakdown(
  plugin: RNPlugin,
  cardPriorityInfos: CardPriorityInfo[],
  weights: number[] | null,
  cardCapMs: number,
  ignorePreReset: boolean,
  period: PeriodSpec,
  onProgress?: (done: number, total: number) => void,
  /** Optional per-card sink — lets an export capture the raw rows behind the aggregates. */
  onRow?: (row: CardAnalyticsRow) => void,
  /**
   * Rem ids suppressed by a paused deck, from lib/paused_decks.ts. Pass null
   * when no scan has run — the paused column then reports 0 and the caller is
   * expected to say so, rather than let "we never looked" read as "none".
   */
  pausedRemIds?: Set<string> | null,
): Promise<CardAnalyticsBreakdown> {
  const { startMs, endMs } = period;
  // Map remId → inherited rem priority. Filter out rems with explicit zero cards.
  const remPriority = new Map<string, number>();
  for (const info of cardPriorityInfos) {
    if (info.cardCount === undefined || info.cardCount > 0) {
      remPriority.set(info.remId, info.priority);
    }
  }

  // Pull every card from the KB (includes disabled/paused — matches batch.ts pattern).
  const allCards = (await plugin.card.getAll()) || [];

  const validCards: any[] = [];
  let cardsSkippedNoPriority = 0;
  for (const c of allCards) {
    if (remPriority.has(c.remId)) validCards.push(c);
    else cardsSkippedNoPriority++;
  }

  // Sort by inherited priority so we can bucket by 1-based index percentile.
  validCards.sort((a, b) => (remPriority.get(a.remId)! - remPriority.get(b.remId)!));

  const N = validCards.length;
  /**
   * Population that DEFINES the deciles. Unscheduled cards are excluded: a
   * disabled card, a table row or a cloze whose markup is gone is not something
   * the user intends to practise, and leaving them in lets them push real cards
   * across percentile boundaries.
   *
   * Cards in a PAUSED deck stay in. Pausing defers a card, it does not demote
   * it — excluding them would shift every other card's percentile when a deck is
   * paused and shift it back when unpaused, so priority would drift as a side
   * effect of a scheduling decision. They keep a real nextRepetitionTime, which
   * is exactly what distinguishes them here.
   *
   * Unscheduled cards are still REPORTED in every bucket (the Unsched column);
   * they are placed by where their priority falls among the ranked cards, so a
   * bucket still accounts for all of its cards. Only bucket SIZE is defined by
   * the ranked population.
   */
  const isUnscheduledCard = (c: any) =>
    c.nextRepetitionTime === null || c.nextRepetitionTime === undefined;
  const rankedTotal = validCards.reduce((n, c) => (isUnscheduledCard(c) ? n : n + 1), 0);
  const rankDenominator = rankedTotal > 0 ? rankedTotal : N;
  let rankedSeen = 0;
  const bucketAccs: AccData[] = Array.from({ length: 10 }, makeAcc);
  const overallAcc = makeAcc();
  // Per-absolute-priority accumulators (priority 0..100, inclusive). Used to
  // produce a prefix-sum table so the threshold slider in the view becomes a
  // pure array lookup instead of re-aggregating on every drag.
  const byPriorityAccs: AccData[] = Array.from({ length: 101 }, makeAcc);
  const now = Date.now();

  const YIELD_EVERY = 1500;

  if (onProgress) onProgress(0, N);

  for (let i = 0; i < N; i++) {
    const card = validCards[i];
    const priority = remPriority.get(card.remId)!;
    // 1-based index percentile over the RANKED population. An unscheduled card
    // takes the percentile of the ranked cards it sits between (the array is
    // sorted by priority, so `rankedSeen` is its lower-bound rank) — it is
    // placed by its priority without being allowed to shift anyone else's.
    const cardIsUnscheduled = isUnscheduledCard(card);
    if (!cardIsUnscheduled) rankedSeen++;
    const percentile = Math.min((Math.max(rankedSeen, 1) / rankDenominator) * 100, 100);
    const bIdx = Math.min(Math.floor(percentile / 10), 9);
    // Clamp priority into [0, 100] for the by-priority bucket index.
    const pIdx = Math.max(0, Math.min(100, Math.round(priority)));

    const isPaused = pausedRemIds ? pausedRemIds.has(card.remId) : false;
    const stats = computeCardStats(
      card, weights, now, cardCapMs, ignorePreReset, startMs, endMs, isPaused,
    );
    accumulate(bucketAccs[bIdx], stats, priority);
    accumulate(overallAcc, stats, priority);
    accumulate(byPriorityAccs[pIdx], stats, priority);

    if (onRow) {
      const nextRep = (card.nextRepetitionTime ?? null) as number | null;
      onRow({
        cardId: card._id,
        remId: card.remId,
        cardType: cardTypeLabel(card.type),
        clozeId:
          card.type && typeof card.type === 'object' && 'clozeId' in card.type
            ? String((card.type as any).clozeId)
            : null,
        priority,
        percentile,
        bucket: `${bIdx * 10}-${(bIdx + 1) * 10}%`,
        isNew: stats.isNew,
        isDue: stats.isDue,
        isStale: stats.isStale,
        scheduleState: nextRep === null ? 'unscheduled' : nextRep <= now ? 'due' : 'scheduled',
        inPausedDeck: isPaused,
        nextRepetitionTime: nextRep,
        createdAt: (card.createdAt ?? null) as number | null,
        ...describeCardHistory(card, ignorePreReset),
      });
    }

    if ((i + 1) % YIELD_EVERY === 0) {
      if (onProgress) onProgress(i + 1, N);
      // Yield to the event loop so the progress bar can repaint.
      await new Promise<void>((resolve) => setTimeout(resolve, 0));
    }
  }

  if (onProgress) onProgress(N, N);

  // Build prefix-sum accumulators: prefixAccs[T] aggregates every card with
  // priority ≤ T. Each entry is then finalized for direct rendering. Sliding
  // becomes an O(1) lookup at the view layer.
  const prefixAccs: AccData[] = new Array(101);
  let running = makeAcc();
  for (let t = 0; t <= 100; t++) {
    running = mergeAcc(running, byPriorityAccs[t]);
    // Clone so the array entries don't share the same underlying object
    // (otherwise every entry would point to the final accumulator).
    prefixAccs[t] = { ...running };
  }
  const byPriorityPrefix: CardBucketStats[] = prefixAccs.map((acc, t) =>
    finalize(acc, `Priority ≤ ${t}`),
  );

  return {
    buckets: bucketAccs.map((acc, i) => finalize(acc, `${i * 10}-${(i + 1) * 10}%`)),
    overall: finalize(overallAcc, 'All KB'),
    totalCards: N,
    computedAt: Date.now(),
    pausedScanApplied: !!pausedRemIds,
    cardsSkippedNoPriority,
    ignorePreReset,
    period: period.id,
    periodStartMs: period.startMs,
    periodEndMs: period.endMs,
    periodCustomStart: period.customStart,
    periodCustomEnd: period.customEnd,
    byPriorityPrefix,
  };
}
